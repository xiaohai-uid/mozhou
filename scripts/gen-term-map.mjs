#!/usr/bin/env node
// gen-term-map.mjs — 由 GLOSSARY.md 生成 docs/term-map.md（中英标识符映射）。
//
// 纪律：每个候选标识符都必须**在源码中真实存在**才算 verified。
// 找不到就标 unverified —— 绝不编造路径或标识符。
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const OUT = "docs/term-map.md";
const SEARCH_ROOTS = ["packages", "apps/web/src", "apps/web/server"];
const SKIP = /node_modules|dist|[.]next|coverage/;

// ---------- 收集源码文件 ----------
const srcFiles = [];
function walk(dir) {
  if (!existsSync(dir)) return;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP.test(e.name)) walk(p); continue; }
    if (/[.](ts|tsx)$/.test(e.name) && !e.name.endsWith(".d.ts")) srcFiles.push(p);
  }
}
for (const r of SEARCH_ROOTS) walk(r);

// ---------- 标识符边界匹配（不用正则，避免转义地雷） ----------
function isWordChar(c) {
  const n = c.charCodeAt(0);
  return (n >= 97 && n <= 122) || (n >= 65 && n <= 90) || (n >= 48 && n <= 57) || c === "_" || c === "$";
}
function findIdentifier(name) {
  for (const file of srcFiles) {
    let lines;
    try { lines = readFileSync(file, "utf8").split("\n"); } catch { continue; }
    for (let i = 0; i < lines.length; i++) {
      let idx = lines[i].indexOf(name);
      while (idx >= 0) {
        const before = idx > 0 ? lines[i][idx - 1] : "";
        const afterIdx = idx + name.length;
        const after = afterIdx < lines[i].length ? lines[i][afterIdx] : "";
        if ((!before || !isWordChar(before)) && (!after || !isWordChar(after))) {
          return { file, line: i + 1, name };
        }
        idx = lines[i].indexOf(name, idx + 1);
      }
    }
  }
  return null;
}

// ---------- 解析 GLOSSARY.md 词条 ----------
const gLines = readFileSync("GLOSSARY.md", "utf8").split("\n");
const terms = [];
for (const line of gLines) {
  const m = line.match(/^\*\*(.+?)\*\*:/);
  if (!m) continue;
  const full = m[1];
  const pm = full.match(/\(([^()]*)\)\s*$/);
  const cn = (pm ? full.slice(0, full.indexOf("(")) : full).trim();
  let en = pm ? pm[1].trim() : "";
  const asciiRun = en.match(/^[A-Za-z][A-Za-z0-9 _-]*/);
  if (asciiRun) en = asciiRun[0].trim();
  terms.push({ cn, en });
}

// ---------- 生成变体并逐一验证 ----------
function variants(en) {
  if (!en) return [];
  const words = en.split(/[\s_-]+/).filter(Boolean);
  if (words.length === 0) return [];
  const pascal = words.map((w) => w[0].toUpperCase() + w.slice(1)).join("");
  // TS 惯例：缩写降级（AI -> Ai, API -> Api）。代码里真实存在的是这一种，
  // 不加此项会漏掉大量核心术语（如 AiContextTier 有 13 处真实引用）。
  const degraded = words
    .map((w, i) => (i === 0 ? w[0].toUpperCase() + w.slice(1).toLowerCase() : w[0].toUpperCase() + w.slice(1)))
    .join("");
  const camel = pascal[0].toLowerCase() + pascal.slice(1);
  const camelDeg = degraded[0].toLowerCase() + degraded.slice(1);
  const snake = words.map((w) => w.toUpperCase()).join("_");
  const kebab = words.map((w) => w.toLowerCase()).join("-");
  return [...new Set([pascal, degraded, camel, camelDeg, snake, kebab, en])];
}

const rows = [];
let verified = 0;
for (const t of terms) {
  let hit = null;
  for (const v of variants(t.en)) {
    const r = findIdentifier(v);
    if (r) { hit = r; break; }
  }
  if (hit) verified++;
  rows.push({ ...t, hit });
}

// ---------- 渲染 ----------
const L = [];
L.push("<!-- Generated by scripts/gen-term-map.mjs - DO NOT EDIT BY HAND. -->");
L.push("<!-- Regenerate: pnpm gen:term-map | Verify freshness: pnpm check:term-map -->");
L.push("");
L.push("# 中英标识符映射表 (Term ↔ Identifier Map)");
L.push("");
L.push("由 [`GLOSSARY.md`](../GLOSSARY.md) 的词条机械生成：取每个词条括号内的英文名，生成 6 种",
      "大小写候选（`PascalCase` / 缩写降级 `AiXxx` / `camelCase` / 缩写降级 camel / `SCREAMING_SNAKE` /",
      "`kebab-case`），再到 `packages/*/src`、`apps/web/src`、`apps/web/server` 里**逐个验证是否真实存在**。");
L.push("");
L.push("**没有匹配到的词条标 `unverified`，绝不编造路径或标识符。** `unverified` 有两种成因，要分开看：");
L.push("");
L.push("1. **该词是流程词，本就没有代码标识符**（如「门 Gate」「契约 Contract」「挂账项」）——正常。");
L.push("2. **该词该有标识符却找不到** —— 这是缺口，值得追。");
L.push("");
L.push("## 统计");
L.push("");
L.push("- 词条总数：**" + terms.length + "**");
L.push("- `verified`（在源码中找到标识符）：**" + verified + "**");
L.push("- `unverified`：**" + (terms.length - verified) + "**");
L.push("");
L.push("## 这张表已经抓到的命名漂移");
L.push("");
L.push("文档里的英文名与代码里的标识符**并非总是一致**，这正是本表存在的理由。已确认的实例：");
L.push("");
L.push("| 术语 | 文档英文名 | 代码实际标识符 | 说明 |");
L.push("|---|---|---|---|");
L.push("| 上下文档位 | `AI Context Tier` | `AiContextTier` | TypeScript 惯例把缩写 `AI` 降级为 `Ai`；直接按 `AIContextTier` 检索会 0 命中 |");
L.push("");
L.push("## 映射表");
L.push("");
L.push("| 规范中文名 | 英文名 | 代码标识符 | 出处 | 状态 |");
L.push("|---|---|---|---|---|");
for (const r of rows) {
  if (r.hit) {
    L.push("| " + r.cn + " | " + r.en + " | `" + r.hit.name + "` | `" + r.hit.file.replace(/\\/g, "/") + ":" + r.hit.line + "` | ✅ |");
  } else {
    L.push("| " + r.cn + " | " + (r.en || "—") + " | — | — | ⚠️ unverified |");
  }
}
L.push("");

const out = L.join("\n");

if (process.argv.indexOf("--check") >= 0) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== out) {
    console.error("STALE: " + OUT + " 与生成器输出不一致。运行: pnpm gen:term-map");
    process.exit(1);
  }
  console.log("FRESH: " + OUT);
} else {
  writeFileSync(OUT, out);
  console.log("WROTE " + OUT + " (" + out.split("\n").length + " lines, terms=" + terms.length + ", verified=" + verified + ", unverified=" + (terms.length - verified) + ")");
}
