#!/usr/bin/env node
// gen-architecture.mjs — 生成 docs/architecture.md（有序地图）。
//   node scripts/gen-architecture.mjs           写入
//   node scripts/gen-architecture.mjs --check   新鲜度门禁，不一致 exit 1
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const OUT = "docs/architecture.md";
const Q = String.fromCharCode(96); // 反引号，避免与模板字符串冲突
const b = (s) => Q + s + Q;

const readJSON = (p) => { try { return JSON.parse(readFileSync(p, "utf8")); } catch { return null; } };

function countLOC(dir, acc = { files: 0, lines: 0, testFiles: 0, testLines: 0 }) {
  if (!existsSync(dir)) return acc;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) { countLOC(p, acc); continue; }
    if (!/\.(ts|tsx|mjs|js|css)$/.test(e.name)) continue;
    if (e.name.endsWith(".d.ts")) continue;
    let n = 0;
    try { n = readFileSync(p, "utf8").split("\n").length; } catch { continue; }
    acc.files++; acc.lines += n;
    if (/\.(test|spec)\.[tj]sx?$/.test(e.name)) { acc.testFiles++; acc.testLines += n; }
  }
  return acc;
}

const wsRaw = readFileSync("pnpm-workspace.yaml", "utf8");
const globs = [...wsRaw.matchAll(/-\s*['"]?([^'"\n]+)['"]?/g)].map((m) => m[1].trim());
const dirs = new Set();
for (const g of globs) {
  const star = g.indexOf("*");
  if (star < 0) continue;
  const base = g.slice(0, star).replace(/\/$/, "");
  for (const e of readdirSync(base, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    const d = join(base, e.name);
    if (existsSync(join(d, "package.json"))) dirs.add(d.replace(/\\/g, "/"));
  }
}

const pkgs = [...dirs].sort().map((dir) => {
  const pkg = readJSON(join(dir, "package.json"));
  if (!pkg) return null;
  const deps = Object.keys(Object.assign({}, pkg.dependencies, pkg.devDependencies))
    .filter((d) => d.startsWith("@mozhou/")).sort();
  return Object.assign({ dir, name: pkg.name, deps }, countLOC(join(dir, "src")));
}).filter(Boolean);

const byName = new Map(pkgs.map((p) => [p.name, p]));
const color = new Map(); const cycles = []; const stack = [];
function dfs(name) {
  color.set(name, 1); stack.push(name);
  for (const d of (byName.get(name) || {}).deps || []) {
    if (!byName.has(d)) continue;
    if (color.get(d) === 1) {
      const i = stack.indexOf(d);
      cycles.push(stack.slice(i).concat(d).join(" -> "));
    } else if (!color.get(d)) dfs(d);
  }
  stack.pop(); color.set(name, 2);
}
for (const p of pkgs) if (!color.get(p.name)) dfs(p.name);

const consumers = new Map(pkgs.map((p) => [p.name, []]));
for (const p of pkgs) for (const d of p.deps) if (consumers.has(d)) consumers.get(d).push(p.name);

const L = [];
L.push("<!-- Generated by scripts/gen-architecture.mjs - DO NOT EDIT BY HAND. -->");
L.push("<!-- Regenerate: node scripts/gen-architecture.mjs | Freshness gate: node scripts/gen-architecture.mjs --check -->");
L.push("");
L.push("# 墨舟架构地图 (Architecture Map)");
L.push("");
L.push("本文件是**生成物**，描述组合关系与依赖拓扑。术语见 " + b("GLOSSARY.md") + "，决策理由见 " + b("docs/adr/INDEX.md") + "。");
L.push("");
L.push("## 1. Workspace");
L.push("");
L.push("| 包 | 路径 | 源码文件 | 源码行数 | 测试文件 | 测试行数 | 内部依赖 |");
L.push("|---|---|---:|---:|---:|---:|---|");
for (const p of pkgs.slice().sort((a, b2) => b2.lines - a.lines)) {
  const deps = p.deps.length ? p.deps.map(b).join(", ") : "—";
  L.push("| " + b(p.name) + " | " + b(p.dir) + " | " + p.files + " | " + p.lines + " | " + p.testFiles + " | " + p.testLines + " | " + deps + " |");
}
L.push("");
L.push("## 2. 依赖边");
L.push("");
L.push("```");
for (const p of pkgs.slice().sort((a, b2) => a.name.localeCompare(b2.name))) {
  L.push(p.name);
  for (const d of p.deps) L.push("  --> " + d);
}
L.push("```");
L.push("");
L.push("## 3. 依赖环");
L.push("");
if (cycles.length === 0) {
  L.push("**无环。** 内部依赖构成有向无环图。");
} else {
  L.push("**检出依赖环：**");
  L.push("");
  for (const c of Array.from(new Set(cycles))) L.push("- " + b(c));
}
L.push("");
L.push("## 4. 零消费者候选");
L.push("");
L.push("按 DSH 判据：只有 Definition + Provider 而零 Consumer 的东西**不是接缝，是死代码**。");
L.push("");
L.push("> 零消费者也可能是「尚未接线」，两者处置相反。**下表是候选清单，不是判决。**");
L.push("");
const zero = pkgs.filter((p) => consumers.get(p.name).length === 0 && p.deps.length > 0);
if (zero.length === 0) {
  L.push("无。（所有有内部依赖的包都至少被一个包消费）");
} else {
  L.push("| 包 | 出向依赖 | 入向消费者 |");
  L.push("|---|---:|---:|");
  for (const p of zero) L.push("| " + b(p.name) + " | " + p.deps.length + " | **0** |");
}
L.push("");
L.push("## 5. 叶子包（零内部依赖）");
L.push("");
const leaves = pkgs.filter((p) => p.deps.length === 0);
L.push(leaves.length ? leaves.map((p) => "- " + b(p.name) + " — " + b(p.dir) + "（" + p.lines + " 行）").join("\n") : "无。");
L.push("");
L.push("## 6. 本生成器**不**覆盖的判据");
L.push("");
L.push("以下需要人读代码，生成器不产出，也**不应被推断**：");
L.push("");
L.push("- 接缝三角色（Definition / Provider / Consumer）的归属——尤其 " + b("packages/runtime") + " 与 " + b("apps/web/server/llm") + " 之间的分层是否为有意设计。");
L.push("- " + b("apps/web/server/") + " 内多个落盘 store 之间的职责边界。");
L.push("- UI 基线 0027 / 0028 / 0029 三代 CSS 同时在树，实际生效的是哪一代（见 ADR-0029）。");
L.push("");

const out = L.join("\n");

if (process.argv.indexOf("--check") >= 0) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== out) {
    console.error("STALE: " + OUT + " 与生成器输出不一致。运行: node scripts/gen-architecture.mjs");
    process.exit(1);
  }
  console.log("FRESH: " + OUT);
} else {
  writeFileSync(OUT, out);
  console.log("WROTE " + OUT + " (" + out.split("\n").length + " lines, " + pkgs.length + " packages, cycles=" + cycles.length + ")");
}
